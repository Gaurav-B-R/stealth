def _stage_label(status_key: str) -> str:
    stage = catalog.CLIENT_STAGE_MAP.get(status_key)
    return stage["label"] if stage else status_key


def _iso(value) -> Optional[str]:
    if value is None:
        return None
    try:
        return value.isoformat()
    except Exception:
        return str(value)


def _client_brief(c: models.EnterpriseClient, member_names: dict | None = None) -> dict:
    assigned = None
    if c.assigned_to_user_id and member_names:
        assigned = member_names.get(int(c.assigned_to_user_id))
    return {
        "id": c.id,
        "name": c.full_name,
        "status": _stage_label(c.status),
        "destination": c.destination_country_name,
        "visa_type": c.visa_type,
        "intake": c.intake,
        "priority": c.priority,
        "key_date": _iso(c.target_date),
        "assigned_to": assigned,
        "email": c.email,
        "phone": c.phone,
    }



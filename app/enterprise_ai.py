def build_org_tools(db: Session, organization_id: int) -> list:
    org_id = int(organization_id)

    def _member_names() -> dict:
        rows = (
            db.query(models.EnterpriseOrganizationMember.user_id, models.User.full_name, models.User.email)
            .join(models.User, models.User.id == models.EnterpriseOrganizationMember.user_id)
            .filter(
                models.EnterpriseOrganizationMember.organization_id == org_id,
                models.EnterpriseOrganizationMember.is_active.is_(True),
            )
            .all()
        )
        return {int(uid): (full or email or "Team member") for uid, full, email in rows}

    def _base():
        return db.query(models.EnterpriseClient).filter(models.EnterpriseClient.organization_id == org_id)

    def get_portal_overview() -> dict:
        """Get a high-level overview of the entire portal: total clients, a breakdown
        by pipeline stage, by visa type, by destination country, how many are approved
        vs rejected, and how many new clients were added this week and this month.
        Use this for broad 'how is my portal doing' style questions."""
        total = _base().count()
        by_status = {k: 0 for k in catalog.CLIENT_STAGE_KEYS}
        for s, n in (_base().with_entities(models.EnterpriseClient.status, func.count(models.EnterpriseClient.id))
                     .group_by(models.EnterpriseClient.status).all()):
            if s in by_status:
                by_status[s] = int(n)
        status_labelled = {_stage_label(k): v for k, v in by_status.items() if v}
        by_country = {}
        for code, n in (_base().with_entities(models.EnterpriseClient.destination_country_name, func.count(models.EnterpriseClient.id))
                        .group_by(models.EnterpriseClient.destination_country_name).all()):
            by_country[code] = int(n)
        by_visa = {}
        for vt, n in (_base().with_entities(models.EnterpriseClient.visa_type, func.count(models.EnterpriseClient.id))
                      .group_by(models.EnterpriseClient.visa_type).all()):
            by_visa[vt] = int(n)
        week_start, _ = _period_range("this_week")
        month_start, _ = _period_range("this_month")
        new_week = _base().filter(models.EnterpriseClient.created_at >= week_start).count()
        new_month = _base().filter(models.EnterpriseClient.created_at >= month_start).count()
        return {
            "total_clients": total,
            "by_status": status_labelled,
            "by_destination_country": by_country,
            "by_visa_type": by_visa,
            "new_clients_last_7_days": new_week,
            "new_clients_last_30_days": new_month,
        }

    def count_clients(
        status: Optional[str] = None,
        destination_country: Optional[str] = None,
        visa_type: Optional[str] = None,
        added_period: Optional[str] = None,
        updated_period: Optional[str] = None,
    ) -> dict:
        """Count clients matching optional filters.
        - status: a pipeline stage such as 'approved', 'rejected', 'submitted',
          'documents', 'interview', 'awaiting decision', 'new lead', 'on hold'.
        - destination_country: country name or 2-letter code (US, CA, UK, AU, DE, IE).
        - visa_type: a substring of the visa type (e.g. 'F-1', 'Study Permit').
        - added_period: filter by when the client was ADDED. One of 'today',
          'yesterday', 'this_week', 'this_month', 'all'.
        - updated_period: filter by when the client's record last CHANGED (a good
          proxy for status changes). Same options as added_period. For example, to
          answer 'how many were approved today', use status='approved' and
          updated_period='today'.
        Returns the matching count and the filters that were applied."""
        q = _base()
        applied = {}
        st = _normalize_status(status)
        if status and st:
            q = q.filter(models.EnterpriseClient.status == st)
            applied["status"] = _stage_label(st)
        code = _normalize_country(destination_country)
        if destination_country and code:
            q = q.filter(models.EnterpriseClient.destination_country_code == code)
            applied["destination_country"] = catalog.COUNTRY_MAP[code]["name"]
        if visa_type:
            q = q.filter(func.lower(models.EnterpriseClient.visa_type).like(f"%{visa_type.strip().lower()}%"))
            applied["visa_type"] = visa_type
        if added_period:
            s, e = _period_range(added_period)
            if s is not None:
                q = q.filter(models.EnterpriseClient.created_at >= s)
            if e is not None:
                q = q.filter(models.EnterpriseClient.created_at < e)
            applied["added_period"] = added_period
        if updated_period:
            s, e = _period_range(updated_period)
            if s is not None:
                q = q.filter(models.EnterpriseClient.updated_at >= s)
            if e is not None:
                q = q.filter(models.EnterpriseClient.updated_at < e)
            applied["updated_period"] = updated_period
        return {"count": int(q.count()), "filters_applied": applied or "none"}

    def search_clients(
        query: Optional[str] = None,
        status: Optional[str] = None,
        destination_country: Optional[str] = None,
        limit: int = 20,
    ) -> dict:
        """Search for clients and return a short list with their key fields.
        - query: matches name, email, phone, passport number or application reference.
        - status: optional pipeline stage filter.
        - destination_country: optional country name or code.
        - limit: max results (default 20, capped at 50).
        Use this to list clients matching a description."""
        q = _base()
        st = _normalize_status(status)
        if status and st:
            q = q.filter(models.EnterpriseClient.status == st)
        code = _normalize_country(destination_country)
        if destination_country and code:
            q = q.filter(models.EnterpriseClient.destination_country_code == code)
        if query and query.strip():
            like = f"%{query.strip().lower()}%"
            q = q.filter(or_(
                func.lower(models.EnterpriseClient.full_name).like(like),
                func.lower(models.EnterpriseClient.email).like(like),
                func.lower(models.EnterpriseClient.phone).like(like),
                # passport_number is encrypted at rest and not substring-searchable.
                func.lower(models.EnterpriseClient.application_reference).like(like),
            ))
        n = max(1, min(int(limit or 20), 50))
        rows = q.order_by(models.EnterpriseClient.created_at.desc()).limit(n).all()
        names = _member_names()
        return {"count": len(rows), "clients": [_client_brief(c, names) for c in rows]}

    def get_client_details(name: Optional[str] = None, client_id: Optional[int] = None) -> dict:
        """Get the full profile for a single client, including contact info, passport,
        visa case, status, assigned counselor, key date, and the most recent notes on
        their file. Provide either the client's name or their client_id. If multiple
        clients match a name, a list of candidates is returned instead."""
        q = _base()
        if client_id:
            client = q.filter(models.EnterpriseClient.id == int(client_id)).first()
        elif name and name.strip():
            matches = q.filter(func.lower(models.EnterpriseClient.full_name).like(f"%{name.strip().lower()}%")).limit(10).all()
            if len(matches) > 1:
                names = _member_names()
                return {"multiple_matches": [_client_brief(c, names) for c in matches]}
            client = matches[0] if matches else None
        else:
            return {"error": "Provide a client name or client_id."}
        if not client:
            return {"error": "No matching client found."}
        names = _member_names()
        notes = (
            db.query(models.EnterpriseClientNote)
            .filter(models.EnterpriseClientNote.client_id == client.id)
            .order_by(models.EnterpriseClientNote.created_at.desc())
            .limit(8).all()
        )
        detail = _client_brief(client, names)
        detail.update({
            "nationality": client.nationality,
            "passport_number": client.passport_number,
            "passport_expiry": _iso(client.passport_expiry),
            "application_reference": client.application_reference,
            "added_on": _iso(client.created_at),
            "last_updated": _iso(client.updated_at),
            "recent_notes": [
                {"by": nt.author_name, "on": _iso(nt.created_at), "note": nt.body} for nt in notes
            ],
        })
        return detail

    def clients_needing_attention(limit: int = 15) -> dict:
        """List clients that likely need staff attention right now, each with a reason.
        Flags: key date overdue or within 14 days while still in an early stage, high or
        urgent priority, on hold, new leads untouched for over 7 days, and missing
        contact details. Results are ranked most-urgent first. Use this for
        'who needs my attention' / 'what should I follow up on' questions."""
        today = date.today()
        names = _member_names()
        open_early = {catalog.STAGE_NEW_LEAD, catalog.STAGE_DOCUMENTS}
        terminal = {catalog.STAGE_APPROVED, catalog.STAGE_REJECTED}
        rows = _base().filter(models.EnterpriseClient.status.notin_(list(terminal))).all()
        scored = []
        now = datetime.utcnow()
        for c in rows:
            reasons = []
            score = 0
            td = c.target_date
            if td:
                days = (td - today).days
                if days < 0:
                    reasons.append(f"Key date passed {abs(days)} day(s) ago"); score += 100 + abs(days)
                elif days <= 14 and c.status in open_early:
                    reasons.append(f"Key date in {days} day(s) but still {_stage_label(c.status).lower()}"); score += 80 - days
                elif days <= 7:
                    reasons.append(f"Key date in {days} day(s)"); score += 40 - days
            if c.priority in ("urgent", "high"):
                reasons.append(f"Marked {c.priority} priority"); score += 50 if c.priority == "urgent" else 30
            if c.status == catalog.STAGE_ON_HOLD:
                reasons.append("On hold"); score += 20
            if c.status == catalog.STAGE_NEW_LEAD and c.created_at:
                created = c.created_at.replace(tzinfo=None) if getattr(c.created_at, "tzinfo", None) else c.created_at
                age = (now - created).days
                if age >= 7:
                    reasons.append(f"New lead untouched for {age} day(s)"); score += 15 + age
            if not (c.email or "").strip() and not (c.phone or "").strip():
                reasons.append("No contact details on file"); score += 10
            if reasons:
                item = _client_brief(c, names)
                item["reasons"] = reasons
                scored.append((score, item))
        scored.sort(key=lambda x: x[0], reverse=True)
        n = max(1, min(int(limit or 15), 40))
        return {"count": len(scored), "clients": [it for _, it in scored[:n]]}

    def list_recent_activity(within_days: int = 7) -> dict:
        """Show recent activity: clients added and notes written within the last N days
        (default 7). Use for 'what's happened recently' / 'any updates this week'."""
        days = max(1, min(int(within_days or 7), 90))
        cutoff = datetime.utcnow() - timedelta(days=days)
        names = _member_names()
        added = _base().filter(models.EnterpriseClient.created_at >= cutoff).order_by(models.EnterpriseClient.created_at.desc()).limit(25).all()
        notes = (
            db.query(models.EnterpriseClientNote, models.EnterpriseClient.full_name)
            .join(models.EnterpriseClient, models.EnterpriseClient.id == models.EnterpriseClientNote.client_id)
            .filter(models.EnterpriseClientNote.organization_id == org_id, models.EnterpriseClientNote.created_at >= cutoff)
            .order_by(models.EnterpriseClientNote.created_at.desc()).limit(25).all()
        )
        return {
            "window_days": days,
            "clients_added": [_client_brief(c, names) for c in added],
            "notes_added": [
                {"client": cname, "by": nt.author_name, "on": _iso(nt.created_at), "note": nt.body}
                for nt, cname in notes
            ],
        }

    def get_team_workload() -> dict:
        """List team members and how many active (non-closed) clients are assigned to
        each, plus how many clients are currently unassigned. Use for workload questions."""
        names = _member_names()
        terminal = [catalog.STAGE_APPROVED, catalog.STAGE_REJECTED]
        counts = dict(
            _base().filter(models.EnterpriseClient.status.notin_(terminal),
                           models.EnterpriseClient.assigned_to_user_id.isnot(None))
            .with_entities(models.EnterpriseClient.assigned_to_user_id, func.count(models.EnterpriseClient.id))
            .group_by(models.EnterpriseClient.assigned_to_user_id).all()
        )
        unassigned = _base().filter(models.EnterpriseClient.status.notin_(terminal),
                                    models.EnterpriseClient.assigned_to_user_id.is_(None)).count()
        workload = [{"member": names.get(int(uid), "Unknown"), "active_clients": int(n)} for uid, n in counts.items()]
        workload.sort(key=lambda x: x["active_clients"], reverse=True)
        return {"team": workload, "unassigned_active_clients": unassigned}

    def _resolve_client_row(name=None, client_id=None):
        q = _base()
        if client_id:
            return q.filter(models.EnterpriseClient.id == int(client_id)).first(), None
        if name and str(name).strip():
            matches = q.filter(func.lower(models.EnterpriseClient.full_name).like(f"%{str(name).strip().lower()}%")).limit(10).all()
            if len(matches) > 1:
                return None, matches
            return (matches[0] if matches else None), None
        return None, None

    def list_client_documents(name: Optional[str] = None, client_id: Optional[int] = None) -> dict:
        """List the documents uploaded for a client (document type, file name, who
        uploaded it and when). Provide the client's name or client_id. Use this for
        'what documents do we have for X' / 'has X uploaded their passport' questions."""
        client, multi = _resolve_client_row(name, client_id)
        if multi:
            return {"multiple_matches": [_client_brief(c) for c in multi]}
        if not client:
            return {"error": "No matching client found."}
        rows = (
            db.query(models.EnterpriseClientDocument)
            .filter(models.EnterpriseClientDocument.client_id == client.id)
            .order_by(models.EnterpriseClientDocument.created_at.desc())
            .all()
        )
        return {
            "client": client.full_name,
            "document_count": len(rows),
            "documents": [
                {
                    "document_type": d.document_type,
                    "file_name": d.original_filename,
                    "uploaded_by": d.uploaded_by_name,
                    "uploaded_on": _iso(d.created_at),
                    "has_readable_text": bool((d.extracted_text or "").strip()),
                }
                for d in rows
            ],
        }

    def read_client_document(name: Optional[str] = None, client_id: Optional[int] = None,
                             document_type: Optional[str] = None) -> dict:
        """Read the extracted TEXT CONTENTS of a client's uploaded document(s) so you can
        answer questions about what's inside them (e.g. passport number/expiry, amounts in
        a bank statement, details in an offer letter). Provide the client's name or
        client_id; optionally pass a document_type (e.g. 'Passport', 'Financial') to narrow
        it down. Only documents whose text has been extracted are returned."""
        client, multi = _resolve_client_row(name, client_id)
        if multi:
            return {"multiple_matches": [_client_brief(c) for c in multi]}
        if not client:
            return {"error": "No matching client found."}
        q = (
            db.query(models.EnterpriseClientDocument)
            .filter(models.EnterpriseClientDocument.client_id == client.id)
        )
        if document_type and document_type.strip():
            q = q.filter(func.lower(models.EnterpriseClientDocument.document_type).like(f"%{document_type.strip().lower()}%"))
        rows = q.order_by(models.EnterpriseClientDocument.created_at.desc()).limit(6).all()
        out = []
        for d in rows:
            txt = (d.extracted_text or "").strip()
            out.append({
                "document_type": d.document_type,
                "file_name": d.original_filename,
                "contents": (txt[:8000] if txt else None),
                "text_available": bool(txt),
            })
        if not out:
            return {"client": client.full_name, "documents": [], "note": "No documents matched."}
        return {"client": client.full_name, "documents": out}

    def list_upcoming_calendar_events(within_days: int = 30, include_done: bool = False) -> dict:
        """List this consultancy's calendar for the near term — use this for any question
        about the schedule, calendar, upcoming events, deadlines, interviews, biometrics,
        appointments, follow-ups, who has something coming up, or what's overdue.

        Includes BOTH team-scheduled events (interviews, appointments, biometrics, document
        deadlines, follow-ups) AND auto-derived client key dates: each active client's
        interview/travel key date, and any client passport expiring in the window. Recently
        overdue items (past ~14 days, not yet done) are included so nothing is missed.
        - within_days: how far ahead to look, 1-180 (default 30).
        - include_done: set true to also include events already marked done.
        """
        try:
            days = max(1, min(int(within_days or 30), 180))
        except Exception:
            days = 30
        today = date.today()
        start = today - timedelta(days=14)   # also surface recently-overdue items
        end = today + timedelta(days=days)

        name_cache: dict = {}

        def _cname(cid):
            if not cid:
                return None
            if cid not in name_cache:
                row = (db.query(models.EnterpriseClient.full_name)
                       .filter(models.EnterpriseClient.id == cid,
                               models.EnterpriseClient.organization_id == organization_id).first())
                name_cache[cid] = row[0] if row else None
            return name_cache[cid]

        events: list = []
        mq = (db.query(models.EnterpriseCalendarEvent)
              .filter(models.EnterpriseCalendarEvent.organization_id == organization_id,
                      models.EnterpriseCalendarEvent.event_date >= start,
                      models.EnterpriseCalendarEvent.event_date <= end))
        if not include_done:
            mq = mq.filter(models.EnterpriseCalendarEvent.is_done.is_(False))
        for ev in mq.order_by(models.EnterpriseCalendarEvent.event_date).all():
            d = ev.event_date
            events.append({
                "date": d.isoformat() if d else None, "time": ev.event_time,
                "title": ev.title, "type": ev.event_type, "client": _cname(ev.client_id),
                "notes": (ev.notes or "")[:200] or None, "done": bool(ev.is_done),
                "overdue": bool(d and d < today and not ev.is_done), "source": "scheduled",
            })
        for c in (db.query(models.EnterpriseClient)
                  .filter(models.EnterpriseClient.organization_id == organization_id,
                          models.EnterpriseClient.target_date.isnot(None),
                          models.EnterpriseClient.target_date >= start,
                          models.EnterpriseClient.target_date <= end,
                          models.EnterpriseClient.status.notin_([catalog.STAGE_APPROVED, catalog.STAGE_REJECTED])).all()):
            d = c.target_date
            events.append({"date": d.isoformat() if d else None, "time": None,
                           "title": f"Key date — {c.full_name}", "type": "client_deadline",
                           "client": c.full_name, "stage": _stage_label(c.status),
                           "overdue": bool(d and d < today), "source": "client_key_date"})
        for c in (db.query(models.EnterpriseClient)
                  .filter(models.EnterpriseClient.organization_id == organization_id,
                          models.EnterpriseClient.passport_expiry.isnot(None),
                          models.EnterpriseClient.passport_expiry >= start,
                          models.EnterpriseClient.passport_expiry <= end).all()):
            d = c.passport_expiry
            events.append({"date": d.isoformat() if d else None, "time": None,
                           "title": f"Passport expiry — {c.full_name}", "type": "passport_expiry",
                           "client": c.full_name, "overdue": bool(d and d < today),
                           "source": "client_key_date"})
        events.sort(key=lambda e: (e["date"] or "", e["time"] or "99:99", e["title"] or ""))
        return {"today": today.isoformat(), "within_days": days,
                "count": len(events), "events": events[:60]}

    return [
        get_portal_overview,
        count_clients,
        search_clients,
        get_client_details,
        clients_needing_attention,
        list_recent_activity,
        get_team_workload,
        list_client_documents,
        read_client_document,
        list_upcoming_calendar_events,
    ]



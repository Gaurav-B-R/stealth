def sanitize_public_ai_text(text: str) -> str:
    """Keep internal provider/model names out of user-visible assistant text."""
    value = str(text or "").strip()
    if not value:
        return value
    return INTERNAL_PROVIDER_DISCLOSURE_PATTERN.sub("Rilono AI", value)



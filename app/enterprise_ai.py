"""
Rilono Enterprise AI assistant.

A Gemini function-calling agent that answers consultancy staff questions about
their own portal ("how many got approved this week?", "who needs my attention?",
"what's the status of Rohan?"). The model is given a set of READ-ONLY tools, each
hard-scoped to the caller's organization_id, so:

  * Tenant isolation is guaranteed — a tool can only ever read the caller's org.
  * Access is read-only by construction — tools only run SELECTs; no writes,
    no raw SQL generated by the model.
  * Answers are accurate — counts/aggregations come from the database, not the LLM.

Reuses the existing Gemini setup in app.utils.gemini_service.

NOTE: this module intentionally does NOT use `from __future__ import annotations`.
The Gemini SDK introspects the tool function signatures at runtime to build their
schemas, which requires real (non-stringized) type annotations.
"""


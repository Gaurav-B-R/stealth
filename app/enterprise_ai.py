def _normalize_status(value: Optional[str]) -> Optional[str]:
    v = str(value or "").strip().lower()
    if not v:
        return None
    if v in catalog.CLIENT_STAGE_KEYS:
        return v
    return _STATUS_SYNONYMS.get(v)


def _normalize_country(value: Optional[str]) -> Optional[str]:
    """Accept a 2-letter code or a country name, return the canonical code."""
    v = str(value or "").strip()
    if not v:
        return None
    if v.upper() in catalog.COUNTRY_CODES:
        return v.upper()
    vl = v.lower()
    for c in catalog.COUNTRIES:
        if c["name"].lower() == vl or c["name"].lower().startswith(vl) or vl in c["name"].lower():
            return c["code"]
    return None


def _period_range(period: Optional[str]) -> tuple[Optional[datetime], Optional[datetime]]:
    """Return (start, end) datetimes for a friendly period label."""
    p = str(period or "").strip().lower().replace("-", "_").replace(" ", "_")
    now = datetime.utcnow()
    start_today = now.replace(hour=0, minute=0, second=0, microsecond=0)
    if p in ("today",):
        return start_today, None
    if p in ("yesterday",):
        return start_today - timedelta(days=1), start_today
    if p in ("this_week", "week", "last_7_days", "last_week", "7_days", "past_week"):
        return now - timedelta(days=7), None
    if p in ("this_month", "month", "last_30_days", "last_month", "30_days", "past_month"):
        return now - timedelta(days=30), None
    if p in ("all", "ever", "all_time", ""):
        return None, None
    return None, None



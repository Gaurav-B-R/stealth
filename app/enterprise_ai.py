# Deep Scan uses a two-stage map-reduce so it scales to any file size without ever
# silently dropping documents or overflowing the model's context:
#   MAP    — one small call per document extracts its audit facts as structured JSON
#            (each call sees ONE document in full → nothing is truncated or dropped).
#   REDUCE — one call cross-references the compact facts of ALL documents at once
#            (structured input stays tiny even for 40+ docs → sharp, complete audit).
# Per-document extractions are cached on the document row (keyed by a text hash), so
# re-scans only re-run the cheap reduce step.

# Read each document in full up to this cap for the MAP step (a whole passport / bank
# statement / offer letter fits comfortably; guards against pathological OCR blobs).
DEEP_SCAN_EXTRACT_MAX_DOC_CHARS = int(os.getenv("DEEP_SCAN_EXTRACT_MAX_DOC_CHARS", "60000") or "60000")
# Safety cap on how many documents a single scan will process.
DEEP_SCAN_MAX_DOCUMENTS = int(os.getenv("DEEP_SCAN_MAX_DOCUMENTS", "40") or "40")
# The REDUCE step only sees compact structured facts, which stay small even for large
# files; this is a generous guardrail, not a real constraint.
DEEP_SCAN_RECONCILE_MAX_CHARS = int(os.getenv("DEEP_SCAN_RECONCILE_MAX_CHARS", "160000") or "160000")

# Bounds for the related-data blocks the full-dossier audit feeds the reduce step.
# Newest-first everywhere; each block is individually capped so no single noisy
# surface (e.g. a long email thread) can crowd the others out of context.
DEEP_SCAN_MAX_NOTES = int(os.getenv("DEEP_SCAN_MAX_NOTES", "30") or "30")
DEEP_SCAN_MAX_EMAILS = int(os.getenv("DEEP_SCAN_MAX_EMAILS", "30") or "30")
DEEP_SCAN_MAX_UNIVERSITIES = int(os.getenv("DEEP_SCAN_MAX_UNIVERSITIES", "20") or "20")
DEEP_SCAN_MAX_INTERVIEWS = int(os.getenv("DEEP_SCAN_MAX_INTERVIEWS", "10") or "10")
DEEP_SCAN_MAX_PAYMENTS = int(os.getenv("DEEP_SCAN_MAX_PAYMENTS", "25") or "25")
DEEP_SCAN_MAX_FINDINGS = int(os.getenv("DEEP_SCAN_MAX_FINDINGS", "60") or "60")


def _deep_scan_generate(system_instruction: str, prompt: str, usage_source: str, model_state: dict):
    """Generate with enterprise model-candidate FALLBACK (mirrors the copilot loop).

    Deep Scan previously pinned to `_enterprise_model_candidates()[0]` with no fallback, so a
    single dead primary id (e.g. `gemini-3.1-pro` 404ing while only `-preview` is live) made the
    whole feature 502. This tries each candidate in order and remembers the first that works in
    `model_state['ok']`, so later calls in the same scan skip the dead ones. Raises RuntimeError
    only if EVERY candidate fails (caller then 502s without charging credits).
    """
    genai = gemini_utils.genai
    candidates = _enterprise_model_candidates()
    ok = model_state.get("ok")
    if ok:
        candidates = [ok] + [c for c in candidates if c != ok]
    last_error = None
    for model_name in candidates:
        try:
            model = genai.GenerativeModel(model_name, system_instruction=system_instruction)
            response = model.generate_content(prompt)
            model_state["ok"] = model_name
            ai_usage.record_gemini_usage(usage_source, model_name, response)
            return response
        except Exception as exc:
            last_error = exc
            logger.warning("Deep Scan model attempt failed (%s): %s", model_name, exc)
            continue
    raise RuntimeError(f"Deep Scan: all model candidates failed ({last_error})")


def _parse_json_object(text: Optional[str]):
    """Best-effort parse of a JSON object from a model response (tolerates code fences / prose)."""
    s = (text or "").strip()
    if not s:
        return None
    s = re.sub(r"^```(?:json)?\s*", "", s, flags=re.IGNORECASE)
    s = re.sub(r"\s*```$", "", s).strip()
    try:
        return json.loads(s)
    except Exception:
        pass
    match = re.search(r"\{.*\}", s, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(0))
        except Exception:
            return None
    return None


def _clip(value, limit: int) -> str:
    """One-line, whitespace-collapsed excerpt of any value (for prompt blocks)."""
    s = re.sub(r"\s+", " ", str(value if value is not None else "")).strip()
    return s[:limit] + ("…" if len(s) > limit else "")


def _strip_html(value) -> str:
    return re.sub(r"<[^>]+>", " ", str(value or ""))


def _inr(paise) -> str:
    try:
        return f"₹{int(paise or 0) / 100:,.0f}"
    except Exception:
        return "₹0"



def test_enterprise_dashboard_assistant_prompt_has_identity_guardrail():
    from app import enterprise_ai
    system = enterprise_ai._system_instruction("Test Org", "Test User", "admin")
    assert "Identity guardrail" in system
    assert "Rilono AI" in system


def test_extension_copilot_prompts_have_identity_guardrail():
    from app import enterprise_copilot
    org = SimpleNamespace(company_name="Test Org")
    staff = SimpleNamespace(full_name="Staff Person", email="s@example.com")
    client = SimpleNamespace(
        full_name="Client Person", destination_country_name="Canada",
        destination_country_code="CA", visa_type="Study Permit",
    )
    staff_prompt = enterprise_copilot.build_system_prompt(
        organization=org, staff_user=staff, role="admin", client=client,
        profile_block="-", documents_block="-", journey_block="",
    )
    client_prompt = enterprise_copilot.build_client_system_prompt(
        organization=org, client=client,
        profile_block="-", documents_block="-", journey_block="",
    )
    for prompt in (staff_prompt, client_prompt):
        assert "Identity guardrail" in prompt
        assert "do not mention Gemini, Google" in prompt


